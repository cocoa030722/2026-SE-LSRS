-- 학생 100명, 좌석 200석(10행 × 20열), 예약 10,000건.
-- 예약 i(0~9999): 좌석 i%200+1, 학생 i%100+1, 좌석마다 50건을 2026-11-27 ~ 12-06 에 하루 5건(06·09·12·15·18시, 2시간) 배치.
-- 상태: 10건 중 1건 CANCELLED, 현재(2026-12-01 10:00) 이전 시작은 CHECKED_IN, 이후는 RESERVED.

INSERT INTO users (user_id, login_id, email, password_hash, role, status, no_show_count, restricted_until, token_version)
SELECT t.i, CONCAT('2026', LPAD(t.i, 4, '0')), CONCAT('p', t.i, '@test.ac.kr'), 'hash', 'STUDENT', 'ACTIVE', 0, NULL, 0
FROM (SELECT a.n + 10 * b.n + 1 AS i
      FROM (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
            UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) a
      CROSS JOIN (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
            UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) b) t;

INSERT INTO seat (seat_id, seat_no, zone, grid_row, grid_col, active)
SELECT t.i + 1, CONCAT(CHAR(65 + t.i DIV 20), '-', LPAD(t.i MOD 20 + 1, 2, '0')), CHAR(65 + t.i DIV 20),
       t.i DIV 20 + 1, t.i MOD 20 + 1, TRUE
FROM (SELECT a.n + 10 * b.n + 100 * c.n AS i
      FROM (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
            UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) a
      CROSS JOIN (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
            UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) b
      CROSS JOIN (SELECT 0 n UNION ALL SELECT 1) c) t
WHERE t.i < 200;

INSERT INTO reservation (user_id, seat_id, start_at, end_at, status, checked_in_at, cancel_reason, canceled_by,
                         penalty_applied, created_at)
SELECT s.i MOD 100 + 1, s.i MOD 200 + 1, s.start_at, s.start_at + INTERVAL 2 HOUR,
       CASE WHEN s.i MOD 10 = 0 THEN 'CANCELLED'
            WHEN s.start_at < '2026-12-01 10:00:00' THEN 'CHECKED_IN'
            ELSE 'RESERVED' END,
       CASE WHEN s.i MOD 10 <> 0 AND s.start_at < '2026-12-01 10:00:00' THEN s.start_at END,
       CASE WHEN s.i MOD 10 = 0 THEN 'OTHER' END,
       CASE WHEN s.i MOD 10 = 0 THEN 'STUDENT' END,
       FALSE, '2026-11-20 00:00:00'
FROM (SELECT t.i,
             TIMESTAMP('2026-11-27 06:00:00')
               + INTERVAL ((t.i DIV 200) DIV 5) DAY
               + INTERVAL (((t.i DIV 200) MOD 5) * 3) HOUR AS start_at
      FROM (SELECT a.n + 10 * b.n + 100 * c.n + 1000 * d.n AS i
            FROM (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
                  UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) a
            CROSS JOIN (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
                  UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) b
            CROSS JOIN (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
                  UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) c
            CROSS JOIN (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
                  UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) d) t) s;
